import { useMemo } from 'react'
import { BadgeCheck, TriangleAlert } from 'lucide-react'
import ScheduleGrid from '../components/ScheduleGrid'
import { fixtures } from '../data/mock'
import { detectConflicts } from '../lib/schedule'

export default function Horario() {
  const conflicts = useMemo(() => detectConflicts(fixtures), [])
  const isClean = conflicts.length === 0

  return (
    <section aria-labelledby="schedule-title" className="flex flex-col gap-6">
      <div className="card-formal p-6">
        <p className="text-sm font-semibold text-navy">Monday to Friday</p>
        <h1 id="schedule-title" className="font-heading mt-1 text-3xl font-semibold">
          Schedule
        </h1>
        <p className="mt-2 max-w-2xl text-ink-muted">
          Generated by round-robin per discipline and validated so no course plays two matches at
          the same hour.
        </p>
        <p className="mt-3">
          {isClean ? (
            <span className="badge-formal">
              <BadgeCheck size={14} aria-hidden="true" /> No conflicts detected
            </span>
          ) : (
            <span className="badge-formal" role="alert">
              <TriangleAlert size={14} aria-hidden="true" /> {conflicts.length} conflicts found
            </span>
          )}
        </p>
      </div>

      <ScheduleGrid fixtures={fixtures} />

      {conflicts.length > 0 && (
        <ul className="card-formal p-4 text-sm text-ink-soft" aria-label="Schedule conflicts">
          {conflicts.map((c) => (
            <li key={c}>{c}</li>
          ))}
        </ul>
      )}
    </section>
  )
}
